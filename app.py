# ── Whisper 및 TTS ──
STT_HINT = "한국어 업무 대화입니다. 주요 용어: 에이블, 김대리, 회의록, 담당 업무, 마감일."
def speech_to_text(audio_file):
    result = client.audio.transcriptions.create(
        model="whisper-1",
        file=("microphone.wav", audio_file.getvalue(), "audio/wav"),
        language="ko",
        prompt=STT_HINT
    )
    return result.text.strip()

def text_to_speech(text):
    response = client.audio.speech.create(
        model="tts-1",
        voice="shimmer",
        input=text[:3500]
    )
    return response.content

# ── 분석 핵심 제어 ──
def analyze(question):
    style = st.session_state.answer_style
    style_rules = {
        "간결": "[응답 모드: 간결] 1~3문장 내외로 요점 위주 작성.",
        "기본": "[응답 모드: 기본] 핵심 설명과 구체적 내역 균형 유지.",
        "상세": "[응답 모드: 상세] 논의 배경부터 마감일, 발언 근거 상세 분석."
    }
    
    system = sys_role + "\n\n" + style_rules[style] + "\n에이블은 귀여운 수달 비서입니다."
    
    if st.session_state.meeting_text:
        system += f"\n\n[회의록]\n<meeting>\n{st.session_state.meeting_text[:50000]}\n</meeting>"
        
    messages = [{"role": "system", "content": system}]
    messages.extend(st.session_state.messages[-10:])
    messages.append({"role": "user", "content": question})
    
    response = client.beta.chat.completions.parse(
        model=MODEL,
        temperature=0,
        messages=messages,
        response_format=AIResult
    )
    return response.choices[0].message.parsed

# ── 데이터 이메일 변환 보완 유틸리티 ──
def valid_email(address):
    return bool(re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", address or ""))

def process_question(question, enable_tts):
    question = question.strip()
    if not question: return
    
    with st.spinner("에이블이 답변을 준비하고 있어요..."):
        result = analyze(question)
        
    answer = result.answer
    if result.intent == "email_send":
        new_mail = result.email.model_dump()
        st.session_state.pending_email = new_mail
        answer = "이메일 초안을 구성 완료했습니다! 아래에서 승인해 주세요. 🦦"
    else:
        st.session_state.pending_email = None
        
    st.session_state.messages.append({"role": "user", "content": question})
    st.session_state.messages.append({"role": "assistant", "content": answer})
    
    if enable_tts:
        try:
            st.session_state.last_audio = text_to_speech(result.voice_answer or answer)
            st.session_state.autoplay_pending = True
        except:
            pass

